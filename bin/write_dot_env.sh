#!/usr/bin/env bash
set -Eeu

# Writes the repo-root .env, which docker-compose auto-loads for ${...}
# substitution and passes into the shared services via env_file. Every app's
# bin/echo_env_vars.sh calls write_dot_env, so they all share this one writer
# and the tracked .env does not change with whichever app wrote it last.
# App-only env-vars live in each app dir's own <app>.env.
#
# The services get their ports through env_file .env, not through a list of
# names under environment:. Writing every PORT line the versioner emits means
# a port for a new service reaches every container with no compose edit.

show_help()
{
  cat <<'EOF'
Usage: bin/write_dot_env.sh [OPTIONS]

Writes the repo-root .env from the ports the versioner image emits, plus the
env-vars every app's services share. Normally sourced by an app's
bin/echo_env_vars.sh, which calls write_dot_env.

Options:
  -h    Show this help

Example:
  bin/write_dot_env.sh
EOF
}

# Writes .env at the root of the repo holding the current directory. The
# versioner image is the single source of truth for every service's port.
write_dot_env()
{
  local -r repo_root="$(git rev-parse --show-toplevel)"
  {
    echo "# This file is generated by bin/write_dot_env.sh"
    docker run --rm cyberdojo/versioner 2>/tmp/log.stderr | grep PORT
    echo CYBER_DOJO_PROMETHEUS=true
    echo CYBER_DOJO_RUNNER_SPARES_PER_NODE=16
  } > "${repo_root}/.env"
}

if [[ "${BASH_SOURCE[0]}" == "${0}" ]]; then
  if [[ "${1:-}" == '-h' ]]; then
    show_help
    exit 0
  fi
  write_dot_env
fi
